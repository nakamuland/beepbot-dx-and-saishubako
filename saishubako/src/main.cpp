String base(uint32_t id) {
    char name[32];
    snprintf(name, sizeof(name), "/SAISHU/%08lu", (unsigned long)id);
    return String(name);
}
String path(uint32_t id, const char* ext) { return base(id) + ext; }

void le16(uint8_t* p, uint16_t n) { p[0] = n; p[1] = n >> 8; }
void le32(uint8_t* p, uint32_t n) {
    for (int i = 0; i < 4; ++i) p[i] = n >> (8 * i);
}
uint32_t read32(const uint8_t* p) {
    return uint32_t(p[0]) | uint32_t(p[1]) << 8 | uint32_t(p[2]) << 16 | uint32_t(p[3]) << 24;
}
bool header(File& f, uint32_t bytes) {
    uint8_t h[44] = {};
    memcpy(h, "RIFF", 4); le32(h + 4, bytes + 36);
    memcpy(h + 8, "WAVEfmt ", 8); le32(h + 16, 16);
    le16(h + 20, 1); le16(h + 22, 1); le32(h + 24, RATE);
    le32(h + 28, RATE * 2); le16(h + 32, 2); le16(h + 34, 16);
    memcpy(h + 36, "data", 4); le32(h + 40, bytes);
    return f.seek(0) && f.write(h, sizeof(h)) == sizeof(h);
}
void message(const String& s) { notice = s; dirty = true; }
void fail(const String& s) { Serial.println(String("ERROR: ") + s); mode = Mode::ERROR; message(s); }

void returnToLauncher() {
    const esp_partition_t* running = esp_ota_get_running_partition();
    if (!running || running->subtype != ESP_PARTITION_SUBTYPE_APP_OTA_1) {
        message("Launcher return requires OTA slot 1");
        return;
    }
    const esp_partition_t* launcher = esp_partition_find_first(
        ESP_PARTITION_TYPE_APP, ESP_PARTITION_SUBTYPE_APP_OTA_0, nullptr);
    if (!launcher || esp_ota_set_boot_partition(launcher) != ESP_OK) {
        message("Launcher slot not available");
        return;
    }
    delay(100);
    esp_restart();
}

// Parse only filenames generated by this application; reserve partial-file IDs too.
uint32_t filenameId(String name) {
    name = name.substring(name.lastIndexOf('/') + 1);
    if (name.length() < 12 || name[8] != '.') return 0;
    uint32_t id = 0;
    for (int i = 0; i < 8; ++i) {
        if (name[i] < '0' || name[i] > '9') return 0;
        id = id * 10 + name[i] - '0';
    }
    return id;
}

void scan() {
    entries.clear();
    File dir = SD.open(ROOT);
    if (!dir || !dir.isDirectory()) { fail("Cannot read SD folder"); return; }
    while (File f = dir.openNextFile()) {
        String name(f.name());
        uint32_t id = filenameId(name);
        if (id && !f.isDirectory()) {
            nextId = std::max(nextId, id + 1);
            if (name.endsWith(".txt") || name.endsWith(".wav") || name.endsWith(".jpg")) entries.push_back(id);
        }
        f.close();
    }
    dir.close();
    std::sort(entries.begin(), entries.end(), std::greater<uint32_t>());
    entries.erase(std::unique(entries.begin(), entries.end()), entries.end());
    if (selected >= (int)entries.size()) selected = std::max(0, (int)entries.size() - 1);
}

// A .part is never overwritten. Recover complete PCM samples after an interrupted take.
bool recover() {
    std::vector<String> names;
    File dir = SD.open(ROOT);
    if (!dir) return false;
    while (File f = dir.openNextFile()) {
        String name(f.name());
        if (!f.isDirectory() && filenameId(name) && name.endsWith(".part")) names.push_back(name);
        f.close();
    }
    dir.close();
    for (auto name : names) {
        uint32_t id = filenameId(name);
        String part = path(id, ".part");
        if (SD.exists(path(id, ".wav"))) return false;
        File f = SD.open(part, "r+");
        if (!f || f.size() < 44) { if (f) f.close(); return false; }
        uint32_t bytes = (f.size() - 44) & ~1U;
        bool ok = header(f, bytes);
        f.flush(); f.close();
        if (!ok || !SD.rename(part, path(id, ".wav"))) return false;
    }
    return true;
}

bool appendDraft(const String& text) {
    if (draft.length() + text.length() > NOTE_BYTES) {
        message("Note full");
        return false;
    }
    draft += text;
    return true;
}

String inputKana(String text) {
    if (inputMode != InputMode::KATAKANA) return text;
    for (unsigned i = 0; i + 2 < text.length(); ++i) {
        if (uint8_t(text[i]) != 0xe3 || !utf8Continuation(text[i + 1]) ||
            !utf8Continuation(text[i + 2])) continue;
        unsigned code = 0x3000 | ((uint8_t(text[i + 1]) & 0x3f) << 6) |
                        (uint8_t(text[i + 2]) & 0x3f);
        if (code < 0x3041 || code > 0x3096) continue;
        code += 0x60;
        text.setCharAt(i + 1, char(0x80 | ((code >> 6) & 0x3f)));
        text.setCharAt(i + 2, char(0x80 | (code & 0x3f)));
        i += 2;
    }
    return text;
}

bool finishRomaji() {
    if (pendingRomaji.isEmpty()) return true;
    if (!appendDraft(pendingRomaji == "n" || pendingRomaji == "nn" ? inputKana("ん") : pendingRomaji)) return false;
    pendingRomaji = "";
    return true;
}

void typeCharacter(char c) {
    if (inputMode == InputMode::ASCII) {
        appendDraft(String(c));
    } else if ((c >= 'a' && c <= 'z') || (c == 39 && pendingRomaji == "n")) {
        String next = pendingRomaji + c;
        String converted = convertRomaji(next);
        if (appendDraft(inputKana(converted))) pendingRomaji = next;
    } else if (finishRomaji()) {
        appendDraft(inputMode == InputMode::KATAKANA && c == '-' ? String("ー") : String(c));
    }
}

bool saveDraft() {
    if (!finishRomaji()) return false;
    if (draft.isEmpty()) {
        if (pendingId) { pendingId = 0; message("Media kept. Ready for next."); }
        else message("Type a note, or Fn+R to record");
        return true;
    }
    uint32_t id = pendingId ? pendingId : nextId++;
    if (id > 99999999) { message("Record number limit"); return false; }
    String tmp = path(id, ".tmp"), dest = path(id, ".txt");
    // Never overwrite an existing note, including an unfinished previous save.
    if (SD.exists(tmp) || SD.exists(dest)) { message("Name conflict; draft kept"); return false; }
    File f = SD.open(tmp, FILE_WRITE);
    if (!f) { message("SD write failed; draft kept"); return false; }
    String text = draft + "\r\n";
    bool ok = f.print(text) == text.length();
    f.flush(); f.close();
    if (!ok || !SD.rename(tmp, dest)) {
        SD.remove(tmp); message("Save failed; draft kept"); return false;
    }
    draft = ""; pendingId = 0;
    message("Collected! / SAISHU SHIMASHITA");
    return true;
}

bool appendPcm(uint8_t index) {
    size_t n = audio.write((uint8_t*)pcm[index], sizeof(pcm[index]));
    audioBytes += n;
    audioBytes &= ~1U;
    return n == sizeof(pcm[index]);
}

void stopRecording(bool ioError = false) {
    // Two buffers are queued at all times. Finish and store the tail before closing.
    if (!ioError) {
        uint32_t started = millis();
        while (M5Cardputer.Mic.isRecording()) {
            delay(1);
            if (millis() - started > 2000) { ioError = true; break; }
        }
        if (!ioError) {
            if (!appendPcm(bufferIndex) || !appendPcm((bufferIndex + 1) % 3)) ioError = true;
        }
    }
    M5Cardputer.Mic.end();
    bool ok = header(audio, audioBytes);
    audio.flush(); audio.close();
    if (!ok || !SD.rename(path(audioId, ".part"), path(audioId, ".wav"))) {
        fail("Finalize failed: keep SD / reboot"); return;
    }
    pendingId = audioId;
    mode = Mode::EDIT;
    message(ioError ? "SD/Mic error; partial audio kept" : "Audio kept! Type label + Enter");
}

void startRecording() {
    if ((!draft.isEmpty() || !pendingRomaji.isEmpty()) && !saveDraft()) return;
    pendingId = 0;
    audioId = nextId++;
    if (audioId > 99999999) { message("Record number limit"); return; }
    String p = path(audioId, ".part");
    if (SD.exists(p) || SD.exists(path(audioId, ".wav"))) { message("Name conflict"); return; }
    audio = SD.open(p, FILE_WRITE);
    if (!audio || !header(audio, 0)) {
        if (audio) { audio.close(); SD.remove(p); }
        message("Cannot create audio on SD"); return;
    }
    audioBytes = 0;
    audio.flush();
    M5Cardputer.Speaker.end();
    if (!M5Cardputer.Mic.begin()) {
        audio.close(); SD.remove(p); message("Mic start failed"); return;
    }
    bufferIndex = 0; level = 0;
    if (!M5Cardputer.Mic.record(pcm[0], SAMPLES, RATE) ||
        !M5Cardputer.Mic.record(pcm[1], SAMPLES, RATE)) {
        stopRecording(true); return;
    }
    mode = Mode::REC; notice = ""; lastFlush = audioProgress = millis(); dirty = true;
}

void recordChunk() {
    if (M5Cardputer.Mic.isRecording() > 1) {
        if (millis() - audioProgress > 2000) stopRecording(true);
        return;
    }
    // Queue a free third buffer before SD I/O; the microphone keeps capturing.
    if (!M5Cardputer.Mic.record(pcm[(bufferIndex + 2) % 3], SAMPLES, RATE)) {
        stopRecording(true); return;
    }
    level = 0;
    for (auto s : pcm[bufferIndex]) level = std::max(level, (uint32_t)abs((int)s));
    if (!appendPcm(bufferIndex)) { stopRecording(true); return; }
    bufferIndex = (bufferIndex + 1) % 3;
    audioProgress = millis();
    if (millis() - lastFlush > 1000) {
        // Refresh the header and return to the end before the next PCM append.
        if (!header(audio, audioBytes) || !audio.seek(44 + audioBytes)) { stopRecording(true); return; }
        audio.flush(); lastFlush = millis();
    }
    if (audioBytes >= MAX_BYTES) stopRecording();
}

String readNote(uint32_t id) {
    File f = SD.open(path(id, ".txt"));
    if (!f) return "";
    String result;
    while (f.available() && result.length() < NOTE_BYTES) {
        char c = f.read();
        if (uint8_t(c) >= 32 && c != 127) result += c;
    }
    f.close(); return result;
}

void stopPlayback() {
    M5Cardputer.Speaker.stop(); M5Cardputer.Speaker.end();
    audio.close(); mode = Mode::VIEW; message("Playback finished");
}
void startPlayback(uint32_t id) {
    audio = SD.open(path(id, ".wav"));
    if (!audio) { message("No audio for this note"); return; }
    uint8_t h[44];
    if (audio.read(h, 44) != 44 || memcmp(h, "RIFF", 4) || memcmp(h + 8, "WAVEfmt ", 8) ||
        read32(h + 16) != 16 || h[20] != 1 || h[21] || h[22] != 1 || h[23] ||
        read32(h + 24) != RATE || h[32] != 2 || h[33] || h[34] != 16 || h[35] ||
        memcmp(h + 36, "data", 4) || read32(h + 40) > audio.size() - 44) {
        audio.close(); message("Unsupported WAV (app files only)"); return;
    }
    audioBytes = read32(h + 40); audioId = id;
    M5Cardputer.Mic.end();
    if (!M5Cardputer.Speaker.begin()) { audio.close(); message("Speaker start failed"); return; }
    M5Cardputer.Speaker.setVolume(100);
    bufferIndex = 0;
    audioProgress = millis();
    mode = Mode::PLAY; message("Playing / Enter: stop");
}
void playChunk() {
    if (!audioBytes) {
        if (M5Cardputer.Speaker.isPlaying()) {
            if (millis() - audioProgress > 2000) { stopPlayback(); message("Speaker timeout"); }
            return;
        }
        stopPlayback(); return;
    }
    // With three buffers, this slot is free once fewer than two requests remain.
    if (M5Cardputer.Speaker.isPlaying(0) > 1) {
        if (millis() - audioProgress > 2000) { stopPlayback(); message("Speaker timeout"); }
        return;
    }
    size_t want = std::min((uint32_t)sizeof(pcm[0]), audioBytes);
    size_t n = audio.read((uint8_t*)pcm[bufferIndex], want);
    if (n != want) { stopPlayback(); message("Audio read failed"); return; }
    if (!M5Cardputer.Speaker.playRaw(pcm[bufferIndex], n / 2, RATE, false, 1, 0)) {
        stopPlayback(); message("Playback failed"); return;
    }
    bufferIndex = (bufferIndex + 1) % 3;
    audioBytes -= n;
    audioProgress = millis();
}

void line(int y, const String& s, uint16_t color = INK) {
    auto& d = M5Cardputer.Display;
    d.setTextColor(color, BG); d.setCursor(5, y); d.print(s);
}
void wrapped(const String& s, int offset = 0) {
    for (int row = 0; row < 7; ++row) {
        int start = offset + row * TEXT_COLUMNS;
        if (start >= (int)utf8Length(s)) break;
        line(25 + row * 11, utf8Slice(s, start, TEXT_COLUMNS));
    }
}
void openCamera(Mode from, uint32_t record = 0) {
    previewBuffer.reset(new(std::nothrow) uint8_t[unitcam::PREVIEW_MAX]);
    if(!previewBuffer) { message("Not enough memory for camera"); return; }
    unitcam::begin();cameraReturn=from;cameraRecord=record;previewAt=0;
    mode=Mode::CAMERA;notice="Connecting UnitCamS3...";dirty=true;
}
void closeCamera() {
    unitcam::port().end();previewBuffer.reset();mode=cameraReturn;dirty=true;
}
void takePhoto() {
    uint32_t id=cameraRecord?cameraRecord:(cameraApp?nextId++:(pendingId?pendingId:nextId++));
    if(id>99999999) {message("Record number limit");return;}
    notice="Saving photo...";
    const char* error=unitcam::save(path(id,".jpg"));
    if(error) {notice=error;dirty=true;return;}
    notice="Photo #"+String(id)+" saved";
    if(!cameraApp) {
        if(cameraReturn==Mode::EDIT) pendingId=id;
        closeCamera();
    } else {scan();dirty=true;}
}
void previewCamera() {
    if(mode!=Mode::CAMERA || !previewBuffer || millis()-previewAt<1000) return;
    size_t length=0;
    const char* error=unitcam::receive(true,previewBuffer.get(),unitcam::PREVIEW_MAX,nullptr,length);
    auto& d=M5Cardputer.Display;
    d.fillRect(0,21,240,96,BG);
    if(!error) d.drawJpg(previewBuffer.get(),length,56,21,128,96,0,0,0.8f,0.8f);
    d.setFont(&fonts::Font0);d.setTextSize(1);
    d.setTextColor(ACCENT_COLOR,BG);d.fillRect(0,109,240,10,BG);
    d.setCursor(4,109);d.print(String(error?error:notice.c_str()).substring(0,38));
    previewAt=millis();
}
